#!/usr/bin/env python3
"""Build the unsigned contact and calendar Shortcut for review."""
import argparse
from pathlib import Path
import plistlib
import subprocess

NAME = "Quick Contact Follow-Up"
PROMPT = ("Create one phone shortcut for a new or existing contact. "
          "Create a calendar entry with an alert as the reminder.")


def build():
    ids = iter(subprocess.check_output(
        ["/bin/zsh", "-c", "for i in {1..50}; do uuidgen | tr '[:lower:]' '[:upper:]'; done"],
        text=True,
    ).splitlines())
    actions = []

    def action(name, output="Result", **params):
        identity = next(ids)
        actions.append({"WFWorkflowActionIdentifier": "is.workflow.actions." + name,
                        "WFWorkflowActionParameters": {"UUID": identity, **params}})
        return {"Type": "ActionOutput", "OutputUUID": identity, "OutputName": output}

    def token(value):
        return {"WFSerializationType": "WFTextTokenAttachment", "Value": value}

    def text(value, *variables):
        placeholders = (i for i, char in enumerate(value) if char == "\ufffc")
        return {"WFSerializationType": "WFTextTokenString", "Value": {
            "string": value,
            "attachmentsByRange": {f"{{{i}, 1}}": var for i, var in zip(placeholders, variables)},
        }}

    def ref(value):
        return text("\ufffc", value)

    def comment(value):
        action("comment", WFCommentActionText=value)

    def set_contact(value):
        action("setvariable", WFVariableName="Contact", WFInput=token(value))

    comment("Choose or create a contact, then make a calendar event with an alert.")
    comment("Shortcuts generated by Shortcuts Playground. May contain mistakes. Always check the shortcut's actions first.\n\n"
            "This shortcut was created via the following user prompt:\n\n> " + PROMPT)
    comment("- Choose a new or existing contact.")
    menu = next(ids)
    action("choosefrommenu", GroupingIdentifier=menu, WFControlFlowMode=0,
           WFMenuPrompt="Contact", WFMenuItems=["Existing contact", "New contact"])
    action("choosefrommenu", GroupingIdentifier=menu, WFControlFlowMode=1,
           WFMenuItemTitle="Existing contact")
    existing = action("selectcontacts", "Contacts", WFSelectMultiple=False)
    set_contact(existing)
    action("choosefrommenu", GroupingIdentifier=menu, WFControlFlowMode=1,
           WFMenuItemTitle="New contact")
    first = action("ask", "Provided Input", WFAskActionPrompt="First name", WFInputType="Text")
    last = action("ask", "Provided Input", WFAskActionPrompt="Last name", WFInputType="Text")
    filters = [{"Operator": 4, "Property": prop, "Removable": True,
                "Values": {"String": ref(value), "Unit": 4}}
               for prop, value in (("First Name", first), ("Last Name", last))]
    matches = action("filter.contacts", "Contacts", WFContentItemFilter={
        "WFSerializationType": "WFContentPredicateTableTemplate", "Value": {
            "WFActionParameterFilterPrefix": 1, "WFContentPredicateBoundedDate": False,
            "WFActionParameterFilterTemplates": filters,
        }})
    comment("- Reuse a matching contact before creating a new one.")
    branch = next(ids)
    action("conditional", GroupingIdentifier=branch, WFControlFlowMode=0, WFCondition=100,
           WFInput={"Type": "Variable", "Variable": token(matches)})
    found = action("choosefromlist", "Chosen Item", WFInput=token(matches),
                   WFChooseFromListActionPrompt="Choose existing contact",
                   WFChooseFromListActionSelectMultiple=False)
    set_contact(found)
    action("conditional", GroupingIdentifier=branch, WFControlFlowMode=1)
    created = action("addnewcontact", "Contact", WFContactFirstName=ref(first),
                     WFContactLastName=ref(last), ShowWhenRun=True)
    set_contact(created)
    action("conditional", GroupingIdentifier=branch, WFControlFlowMode=2)
    action("choosefrommenu", GroupingIdentifier=menu, WFControlFlowMode=2)
    person = {"Type": "Variable", "VariableName": "Contact"}
    name = action("properties.contacts", "Contact Detail", WFInput=token(person),
                  WFContentItemPropertyName="Name")
    phone = action("properties.contacts", "Contact Detail", WFInput=token(person),
                   WFContentItemPropertyName="Phone Numbers")
    title = action("ask", "Provided Input", WFAskActionPrompt="What do you need to do?", WFInputType="Text")
    start = action("ask", "Provided Input", WFAskActionPrompt="When?", WFInputType="Date and Time")
    end = action("adjustdate", "Adjusted Date", WFDate=ref(start), WFAdjustOperation="Add",
                 WFDuration={"WFSerializationType": "WFQuantityFieldValue",
                             "Value": {"Magnitude": 15.0, "Unit": "min"}})
    comment("- Add the selected contact to the event notes.")
    action("addnewevent", "Calendar Event", WFCalendarItemTitle=ref(title),
           WFCalendarItemNotes=text("Contact: \ufffc\nPhone: \ufffc", name, phone),
           WFCalendarItemStartDate=ref(start), WFCalendarItemEndDate=ref(end),
           WFAlertTime="15 minutes before", ShowWhenRun=True)
    return {"WFWorkflowName": NAME, "WFWorkflowActions": actions,
            "WFWorkflowClientVersion": "2700.0.4", "WFWorkflowMinimumClientVersion": 900,
            "WFWorkflowMinimumClientVersionString": "900", "WFWorkflowHasOutputFallback": False,
            "WFWorkflowIcon": {"WFWorkflowIconGlyphNumber": 61464, "WFWorkflowIconStartColor": 3031607807},
            "WFWorkflowImportQuestions": [], "WFWorkflowInputContentItemClasses": [],
            "WFWorkflowOutputContentItemClasses": [], "WFWorkflowTypes": []}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    output = args.output.resolve()
    permitted = Path("/Volumes/HomeSSD/Generated/SINGLETON_SYSTEMS/references").resolve()
    if not output.is_relative_to(permitted):
        raise SystemExit("Choose the verified Singleton Systems references route.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(plistlib.dumps(build(), sort_keys=False))
    print(output)
