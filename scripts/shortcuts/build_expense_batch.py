#!/usr/bin/env python3
"""Build the share-sheet expense Shortcut without embedding credentials."""
import argparse
import plistlib
import uuid
from pathlib import Path


def build(base_url):
    actions = []

    def action(name, output="Text", **params):
        ident = str(uuid.uuid4()).upper()
        actions.append({"WFWorkflowActionIdentifier": "is.workflow.actions." + name,
                        "WFWorkflowActionParameters": {"UUID": ident, **params}})
        return {"Type": "ActionOutput", "OutputUUID": ident, "OutputName": output}

    def attachment(value):
        return {"WFSerializationType": "WFTextTokenAttachment", "Value": value}

    def text(template, *values):
        iterator = iter(values)
        return {"WFSerializationType": "WFTextTokenString", "Value": {"string": template,
                "attachmentsByRange": {"{%d, 1}" % i: next(iterator) for i, c in enumerate(template) if c == "\ufffc"}}}

    def fields(items):
        return {"WFSerializationType": "WFDictionaryFieldValue", "Value": {"WFDictionaryFieldValueItems": [
            {"WFKey": text(key), "WFItemType": 0, "WFValue": value if isinstance(value, dict) else text(value)} for key, value in items]}}

    def get(dictionary, key):
        return action("getvalueforkey", "Dictionary Value", WFInput=attachment(dictionary), WFGetDictionaryValueType="Value", WFDictionaryKey=key)

    def condition(variable, value):
        group = str(uuid.uuid4()).upper()
        action("conditional", GroupingIdentifier=group, WFControlFlowMode=0, WFCondition=4,
               WFInput={"Type": "Variable", "Variable": attachment(variable)}, WFConditionalActionString=value)
        return group

    action("comment", WFCommentActionText="Share screenshots to review and save expense entries.")
    action("comment", WFCommentActionText="Shortcuts generated by Shortcuts Playground. May contain mistakes. Always check the shortcut's actions first.\n\nThis shortcut was created via the following user prompt:\n\n> Share one or more screenshots, add a note, review the entries, then confirm once to save.")
    note = action("ask", "Provided Input", WFAskActionPrompt="Add a note, or leave blank", WFInputType="Text")
    encoded_note = action("base64encode", "Base64 Encoded", WFInput=attachment(note), WFEncodeMode="Encode", WFBase64LineBreakMode="None")
    group = str(uuid.uuid4()).upper()
    action("comment", WFCommentActionText="Prepare each screenshot for Codex.\n- Input uses the shared screenshots.")
    action("repeat.each", GroupingIdentifier=group, WFControlFlowMode=0, WFInput=attachment({"Type": "ExtensionInput"}))
    item = {"Type": "Variable", "VariableName": "Repeat Item"}
    image = action("image.convert", "Converted Image", WFInput=attachment(item), WFImageFormat="JPEG", WFImagePreserveMetadata=False)
    encoded = action("base64encode", "Base64 Encoded", WFInput=attachment(image), WFEncodeMode="Encode", WFBase64LineBreakMode="None")
    quoted = action("gettext", WFTextActionText=text('"\ufffc"', encoded))
    action("appendvariable", WFVariableName="Encoded Images", WFInput=attachment(quoted))
    action("repeat.each", GroupingIdentifier=group, WFControlFlowMode=2)
    joined = action("text.combine", "Combined Text", text=attachment({"Type": "Variable", "VariableName": "Encoded Images"}), WFTextSeparator="Custom", WFTextCustomSeparator=",")
    body = action("gettext", WFTextActionText=text('{"images":[\ufffc],"note64":"\ufffc"}', joined, encoded_note))
    response = action("downloadurl", "Contents of URL", WFURL=base_url + "/prepare", WFHTTPMethod="POST", WFHTTPBodyType="File",
                      WFHTTPHeaders=fields([("Content-Type", "application/json")]), WFRequestVariable=attachment(body))
    parsed = action("detect.dictionary", "Dictionary", WFInput=attachment(response))
    status = action("gettext", WFTextActionText=text("\ufffc", get(parsed, "status")))
    action("comment", WFCommentActionText="Show the review before saving.\n- Condition checks the review status.")
    group = condition(status, "review")
    summary = get(parsed, "summary")
    identity = get(parsed, "id")
    action("alert", WFAlertActionTitle="Save these expenses?", WFAlertActionMessage=text("\ufffc", summary), WFAlertActionCancelButtonShown=True)
    saved = action("downloadurl", "Contents of URL", WFURL=base_url + "/confirm", WFHTTPMethod="POST", WFHTTPBodyType="JSON",
                   WFHTTPHeaders=fields([("Content-Type", "application/json")]), WFJSONValues=fields([("id", text("\ufffc", identity))]))
    receipt = action("detect.dictionary", "Dictionary", WFInput=attachment(saved))
    saved_status = action("gettext", WFTextActionText=text("\ufffc", get(receipt, "status")))
    action("comment", WFCommentActionText="Show the save result.\n- Condition checks the save status.")
    inner = condition(saved_status, "saved")
    balance = get(receipt, "balance")
    action("showresult", Text=text("Saved. Balance: $\ufffc", balance))
    action("conditional", GroupingIdentifier=inner, WFControlFlowMode=1)
    action("showresult", Text="Save was not confirmed. Check Finances before trying again.")
    action("conditional", GroupingIdentifier=inner, WFControlFlowMode=2)
    action("conditional", GroupingIdentifier=group, WFControlFlowMode=1)
    action("showresult", Text=text("Check the screenshot and note, then try again.\n\ufffc", response))
    action("conditional", GroupingIdentifier=group, WFControlFlowMode=2)
    return {"WFWorkflowName": "Add expenses", "WFWorkflowActions": actions, "WFWorkflowClientVersion": "2600",
            "WFWorkflowMinimumClientVersion": 900, "WFWorkflowMinimumClientVersionString": "900", "WFWorkflowHasOutputFallback": False,
            "WFWorkflowIcon": {"WFWorkflowIconGlyphNumber": 59395, "WFWorkflowIconStartColor": 4274264319},
            "WFWorkflowImportQuestions": [], "WFWorkflowInputContentItemClasses": ["WFImageContentItem"],
            "WFWorkflowOutputContentItemClasses": [], "WFWorkflowTypes": ["ActionExtension"]}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--base-url", required=True)
    args = parser.parse_args()
    if not args.base_url.startswith("https://") or not args.base_url.endswith(":8443"):
        raise SystemExit("Use the private Tailscale HTTPS address on port 8443.")
    args.output.write_bytes(plistlib.dumps(build(args.base_url.rstrip("/")), sort_keys=False))
