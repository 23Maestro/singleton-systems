#!/usr/bin/env python3
"""Build the iOS share-sheet Shortcut for Singleton Systems Codex."""
import argparse
import plistlib
from pathlib import Path
import uuid


def build(base):
    actions = []
    def act(name, output="Text", **params):
        ident = str(uuid.uuid4()).upper()
        actions.append({"WFWorkflowActionIdentifier": "is.workflow.actions." + name, "WFWorkflowActionParameters": {"UUID": ident, **params}})
        return {"Type": "ActionOutput", "OutputUUID": ident, "OutputName": output}
    def ref(value): return {"WFSerializationType": "WFTextTokenAttachment", "Value": value}
    def text(value, *args):
        it = iter(args)
        return {"WFSerializationType": "WFTextTokenString", "Value": {"string": value, "attachmentsByRange": {"{%d, 1}" % i: next(it) for i, c in enumerate(value) if c == "\ufffc"}}}
    def fields(items):
        return {"WFSerializationType": "WFDictionaryFieldValue", "Value": {"WFDictionaryFieldValueItems": [{"WFKey": text(k), "WFItemType": 0, "WFValue": text(v)} for k, v in items]}}
    def setvar(name, value): act("setvariable", WFVariableName=name, WFInput=ref(value))
    def condition(variable, code, value):
        group = str(uuid.uuid4()).upper()
        act("conditional", GroupingIdentifier=group, WFControlFlowMode=0, WFCondition=code, WFInput={"Type": "Variable", "Variable": ref(variable)}, WFConditionalActionString=value)
        return group
    def encoded(value): return act("base64encode", "Base64 Encoded", WFInput=ref(value), WFEncodeMode="Encode", WFBase64LineBreakMode="None")
    act("comment", WFCommentActionText="Share a link or screenshot with a note to a new Singleton Systems Codex thread.")
    act("comment", WFCommentActionText="Shortcuts generated by Shortcuts Playground. May contain mistakes. Always check the shortcut's actions first.\n\nThis shortcut was created via the following user prompt:\n\n> Share a social link or screenshot with simple context to a new Singleton Systems Codex thread.")
    note = act("ask", "Provided Input", WFAskActionPrompt="What should Codex do?", WFInputType="Text", WFAllowsMultilineText=True)
    note64 = encoded(note)
    source = {"Type": "ExtensionInput"}
    kind = act("getitemtype", "Type", WFInput=ref(source))
    kindtext = act("text.changecase", "Updated Text", text=text("\ufffc", kind), WFCaseType="lowercase")
    act("comment", WFCommentActionText="Choose how to prepare the shared item.\n- Condition checks the shared item's type.")
    group = condition(kindtext, 99, "image")
    loop = str(uuid.uuid4()).upper()
    act("comment", WFCommentActionText="Prepare each screenshot.\n- Input uses the shared images.")
    act("repeat.each", GroupingIdentifier=loop, WFControlFlowMode=0, WFInput=ref(source))
    image = act("image.convert", "Converted Image", WFInput=ref({"Type": "Variable", "VariableName": "Repeat Item"}), WFImageFormat="JPEG", WFImagePreserveMetadata=False)
    item64 = encoded(image)
    quoted = act("gettext", WFTextActionText=text('"\ufffc"', item64))
    act("appendvariable", WFVariableName="Encoded Images", WFInput=ref(quoted))
    act("repeat.each", GroupingIdentifier=loop, WFControlFlowMode=2)
    joined = act("text.combine", "Combined Text", text=ref({"Type": "Variable", "VariableName": "Encoded Images"}), WFTextSeparator="Custom", WFTextCustomSeparator=",")
    image_body = act("gettext", WFTextActionText=text('{"images":[\ufffc],"text64":"","note64":"\ufffc"}', joined, note64))
    setvar("Share Body", image_body)
    act("conditional", GroupingIdentifier=group, WFControlFlowMode=1)
    shared = act("detect.text", "Text", WFInput=ref(source))
    shared64 = encoded(shared)
    text_body = act("gettext", WFTextActionText=text('{"images":[],"text64":"\ufffc","note64":"\ufffc"}', shared64, note64))
    setvar("Share Body", text_body)
    act("conditional", GroupingIdentifier=group, WFControlFlowMode=2)
    response = act("downloadurl", "Contents of URL", WFURL=base + "/share", WFHTTPMethod="POST", WFHTTPBodyType="File", WFHTTPHeaders=fields([("Content-Type", "application/json")]), WFRequestVariable=ref({"Type": "Variable", "VariableName": "Share Body"}))
    dictionary = act("detect.dictionary", "Dictionary", WFInput=ref(response))
    status = act("getvalueforkey", "Dictionary Value", WFInput=ref(dictionary), WFGetDictionaryValueType="Value", WFDictionaryKey="status")
    status_text = act("gettext", WFTextActionText=text("\ufffc", status))
    act("comment", WFCommentActionText="Review expenses before saving.\n- Condition checks the returned status.")
    group = condition(status_text, 4, "review")
    summary = act("getvalueforkey", "Dictionary Value", WFInput=ref(dictionary), WFGetDictionaryValueType="Value", WFDictionaryKey="summary")
    identity = act("getvalueforkey", "Dictionary Value", WFInput=ref(dictionary), WFGetDictionaryValueType="Value", WFDictionaryKey="id")
    act("alert", WFAlertActionTitle="Save these expenses?", WFAlertActionMessage=text("\ufffc", summary), WFAlertActionCancelButtonShown=True)
    confirm_fields = {"WFSerializationType": "WFDictionaryFieldValue", "Value": {"WFDictionaryFieldValueItems": [{"WFKey": text("id"), "WFItemType": 0, "WFValue": text("\ufffc", identity)}]}}
    saved = act("downloadurl", "Contents of URL", WFURL=base + "/confirm", WFHTTPMethod="POST", WFHTTPBodyType="JSON", WFHTTPHeaders=fields([("Content-Type", "application/json")]), WFJSONValues=confirm_fields)
    receipt = act("detect.dictionary", "Dictionary", WFInput=ref(saved))
    saved_status = act("getvalueforkey", "Dictionary Value", WFInput=ref(receipt), WFGetDictionaryValueType="Value", WFDictionaryKey="status")
    status_value = act("gettext", WFTextActionText=text("\ufffc", saved_status))
    act("comment", WFCommentActionText="Show the save result.\n- Condition checks the returned status.")
    check = condition(status_value, 4, "saved")
    balance = act("getvalueforkey", "Dictionary Value", WFInput=ref(receipt), WFGetDictionaryValueType="Value", WFDictionaryKey="balance")
    act("showresult", Text=text("Saved. Balance: $\ufffc", balance))
    act("conditional", GroupingIdentifier=check, WFControlFlowMode=1)
    act("showresult", Text="Save was not confirmed. Check Finances before trying again.")
    act("conditional", GroupingIdentifier=check, WFControlFlowMode=2)
    act("conditional", GroupingIdentifier=group, WFControlFlowMode=1)
    act("comment", WFCommentActionText="Show whether Codex started the request.\n- Condition checks the returned status.")
    check = condition(status_text, 4, "started")
    act("showresult", Text="Sent to Codex. Open Remote to follow the new task.")
    act("conditional", GroupingIdentifier=check, WFControlFlowMode=1)
    act("showresult", Text=text("Check the share and note, then try again.\n\ufffc", response))
    act("conditional", GroupingIdentifier=check, WFControlFlowMode=2)
    act("conditional", GroupingIdentifier=group, WFControlFlowMode=2)
    return {"WFWorkflowName": "Send to Codex", "WFWorkflowActions": actions, "WFWorkflowClientVersion": "2600", "WFWorkflowMinimumClientVersion": 900,
            "WFWorkflowMinimumClientVersionString": "900", "WFWorkflowHasOutputFallback": False, "WFWorkflowIcon": {"WFWorkflowIconGlyphNumber": 61468, "WFWorkflowIconStartColor": 463140863},
            "WFWorkflowImportQuestions": [], "WFWorkflowInputContentItemClasses": ["WFImageContentItem", "WFURLContentItem", "WFStringContentItem"],
            "WFWorkflowOutputContentItemClasses": [], "WFWorkflowTypes": ["ActionExtension"]}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--base-url", required=True)
    args = parser.parse_args()
    if not args.base_url.startswith("https://") or not args.base_url.endswith(":8443"): raise SystemExit("Use private Tailscale HTTPS port 8443.")
    args.output.write_bytes(plistlib.dumps(build(args.base_url.rstrip("/")), sort_keys=False))
