#!/usr/bin/env python3
"""Build the unsigned finance-entry Shortcut. The key is configured after review."""
import argparse
from pathlib import Path
import plistlib
import subprocess
import uuid

ROOT = Path(__file__).resolve().parents[2]
NAME = "Add Finance Entry"
CATEGORIES = ["Food", "Transportation", "Health", "Household", "Family", "Work", "Personal", "Miscellaneous"]


def build():
    actions = []

    def action(identifier, **parameters):
        identity = str(uuid.uuid4()).upper()
        actions.append({"WFWorkflowActionIdentifier": "is.workflow.actions." + identifier,
                        "WFWorkflowActionParameters": {"UUID": identity, **parameters}})
        return {"Type": "ActionOutput", "OutputUUID": identity, "OutputName": {
            "ask": "Provided Input", "choosefromlist": "Chosen Item", "date": "Date",
            "format.date": "Formatted Date", "downloadurl": "Contents of URL",
            "detect.dictionary": "Dictionary", "getvalueforkey": "Dictionary Value", "list": "List",
        }.get(identifier, "Text")}

    def text(value, *variables):
        refs = iter(variables)
        positions = {"{%d, 1}" % index: next(refs) for index, character in enumerate(value) if character == "\ufffc"}
        return {"WFSerializationType": "WFTextTokenString", "Value": {"string": value, "attachmentsByRange": positions}}

    def ref(variable):
        return text("\ufffc", variable)

    def input_ref(variable):
        return {"WFSerializationType": "WFTextTokenAttachment", "Value": variable}

    def comment(value):
        action("comment", WFCommentActionText=value)

    def fields(items):
        return {"WFSerializationType": "WFDictionaryFieldValue", "Value": {"WFDictionaryFieldValueItems": [
            {"WFKey": text(key), "WFItemType": kind, "WFValue": value if isinstance(value, dict) else text(value)}
            for key, value, kind in items]}}

    def choose(values, prompt):
        source = action("list", WFItems=values)
        return action("choosefromlist", WFInput=input_ref(source), WFChooseFromListActionPrompt=prompt,
                      WFChooseFromListActionSelectMultiple=False)

    def condition(variable, code, string=None):
        group = str(uuid.uuid4()).upper()
        parameters = {"GroupingIdentifier": group, "WFControlFlowMode": 0, "WFCondition": code,
                      "WFInput": {"Type": "Variable", "Variable": {"WFSerializationType": "WFTextTokenAttachment", "Value": variable}}}
        if string is not None:
            parameters["WFConditionalActionString"] = string
        action("conditional", **parameters)
        return group

    def set_variable(name, variable):
        action("setvariable", WFVariableName=name, WFInput=input_ref(variable))
        return {"Type": "Variable", "VariableName": name}

    comment("Save an entry to Finances.")
    comment("Shortcuts generated by Shortcuts Playground.")
    comment("Private key for singleton-systems.com.")
    key = action("gettext", WFTextActionText="PASTE_FINANCE_SHORTCUT_KEY_HERE")
    comment("- Stop if the key is missing.")
    group = condition(key, 4, "PASTE_FINANCE_SHORTCUT_KEY_HERE")
    action("showresult", Text="Finance key missing.")
    action("exit")
    action("conditional", GroupingIdentifier=group, WFControlFlowMode=2)

    expense = "🔴 Expense"
    label = choose([expense, "🟢 Income"], "Type")
    name = action("ask", WFAskActionPrompt="Name", WFInputType="Text")
    amount = action("ask", WFAskActionPrompt="Amount", WFInputType="Number", WFAskActionAllowsDecimalNumbers=True, WFAskActionAllowsNegativeNumbers=False)
    comment("- Ask for a category for expenses.")
    group = condition(label, 4, expense)
    kind = set_variable("Type", action("gettext", WFTextActionText="expense"))
    category = set_variable("Category", choose(CATEGORIES, "Categories"))
    action("conditional", GroupingIdentifier=group, WFControlFlowMode=1)
    set_variable("Type", action("gettext", WFTextActionText="income"))
    set_variable("Category", action("gettext", WFTextActionText="Miscellaneous"))
    action("conditional", GroupingIdentifier=group, WFControlFlowMode=2)
    now = action("date", WFDateActionMode="Current Date")
    date = action("ask", WFAskActionPrompt="Date", WFInputType="Date", WFAskActionDefaultAnswer=ref(now))
    day = action("format.date", WFDate=ref(date), WFDateFormatStyle="Custom", WFDateFormat="yyyy-MM-dd")
    # Each manual run gets a millisecond timestamp. Keep it unchanged within the request.
    capture = action("date", WFDateActionMode="Current Date")
    request_id = action("format.date", WFDate=ref(capture), WFDateFormatStyle="Custom", WFDateFormat="yyyy-MM-dd'T'HH:mm:ss.SSSXXXXX")
    action("alert", WFAlertActionTitle="Save entry?", WFAlertActionMessage=text("\ufffc · $\ufffc\n\ufffc\n\ufffc", label, amount, name, day), WFAlertActionCancelButtonShown=True)
    comment("Send the entry to Finances.")
    response = action("downloadurl", WFURL="https://www.singleton-systems.com/api/finances/entries", WFHTTPMethod="POST", WFHTTPBodyType="JSON", ShowHeaders=False,
                      WFHTTPHeaders=fields([("Authorization", text("Bearer \ufffc", key), 0), ("Content-Type", "application/json", 0)]),
                      WFJSONValues=fields([("requestId", ref(request_id), 0), ("type", ref(kind), 0), ("name", ref(name), 0), ("amount", ref(amount), 3), ("category", ref(category), 0), ("date", ref(day), 0)]))
    parsed = action("detect.dictionary", WFInput=input_ref(response))
    status = action("getvalueforkey", WFInput=input_ref(parsed), WFGetDictionaryValueType="Value", WFDictionaryKey="status")
    status_text = action("gettext", WFTextActionText=ref(status))
    comment("- Show the result of the save.")
    group = condition(status_text, 4, "saved")
    action("showresult", Text="Saved.")
    action("conditional", GroupingIdentifier=group, WFControlFlowMode=1)
    action("showresult", Text="Check Finances before retrying.")
    action("conditional", GroupingIdentifier=group, WFControlFlowMode=2)
    return {"WFWorkflowName": NAME, "WFWorkflowActions": actions, "WFWorkflowClientVersion": "2600",
            "WFWorkflowMinimumClientVersion": 900, "WFWorkflowMinimumClientVersionString": "900",
            "WFWorkflowHasOutputFallback": False, "WFWorkflowIcon": {"WFWorkflowIconGlyphNumber": 59395, "WFWorkflowIconStartColor": 4274264319},
            "WFWorkflowImportQuestions": [], "WFWorkflowInputContentItemClasses": [],
            "WFWorkflowOutputContentItemClasses": [], "WFWorkflowTypes": []}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    route = subprocess.check_output(["node", "scripts/developer-storage/storage-gate.mjs", "route", "--client", "SINGLETON_SYSTEMS", "--kind", "references"], cwd=ROOT, text=True).strip()
    output = args.output.resolve()
    if not output.is_relative_to(Path(route).resolve()):
        raise SystemExit("Choose an output under the verified references route.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(plistlib.dumps(build(), sort_keys=False))
    print(output)
