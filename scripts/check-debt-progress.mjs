import assert from "node:assert/strict";
import { applyCommand, commandSchema } from "../lib/ledger/commands.ts";
import { paidOff, debtRemaining } from "../lib/ledger/progress.ts";
import { isDueOn, lastDueDate } from "../lib/ledger/schedule.ts";
const id = () => crypto.randomUUID();
const debt = { id: "test-debt", name: "Installment", amount: 0, balance: 200, paymentAmount: 100, planType: "debt", isActive: true, dueDate: "2026-01-31", dueDay: 31, recurrence: "monthly", paymentsRemaining: 2, notes: "" };
const base = { balanceSet: true, currentBalance: 500, transactions: [], plannedPayments: [], planEntries: [debt] };
const run = (data, command) => applyCommand(data, commandSchema.parse(command), "2026-10-24T12:00:00Z");
const pay = { type: "payment", id: id(), entryId: debt.id, amount: 50, date: "2026-01-31" };
assert.throws(() => run(base, pay), /Choose Yes or No/);
assert.equal(isDueOn(debt, "2026-01-31"), true);
assert.equal(isDueOn(debt, "2026-02-28"), true);
assert.equal(isDueOn(debt, "2026-03-31"), false);
assert.equal(lastDueDate(debt), "2026-02-28");
assert.equal(isDueOn({ ...debt, paymentsRemaining: 0 }, "2026-01-31"), false);
assert.equal(isDueOn({ ...debt, paymentsRemaining: undefined, repeatUntil: "2026-02-28" }, "2026-02-28"), true);
assert.equal(isDueOn({ ...debt, paymentsRemaining: undefined, repeatUntil: "2026-02-28" }, "2026-03-31"), false);
const weekly = { ...debt, dueDate: "2026-10-25", recurrence: "weekly", paymentsRemaining: 2 };
assert.equal(isDueOn(weekly, "2026-11-01"), true);
assert.equal(isDueOn(weekly, "2026-11-08"), false);
const twice = { ...debt, dueDate: "2026-02-28", recurrence: "semimonthly", dueDay: 30, secondDueDay: 31, paymentsRemaining: 2 };
assert.equal(isDueOn(twice, "2026-02-28"), true);
assert.equal(isDueOn(twice, "2026-03-30"), true);
assert.equal(isDueOn(twice, "2026-03-31"), false);
for (const planType of ["bill", "subscription", "advance"]) assert.throws(() => run({ ...base, planEntries: [] }, { type: "save-item", id: id(), entry: { ...debt, planType } }), /debts only/);
assert.throws(() => run(base, { type: "save-item", id: id(), previous: debt, entry: { ...debt, repeatUntil: "2026-02-28" } }), /payment count or an end date/);
assert.throws(() => commandSchema.parse({ type: "save-item", id: id(), entry: { ...debt, paymentsRemaining: 1.5 } }));
let data = run(base, { type: "debt-progress", id: id(), opening: true, amount: 123.45, date: "2026-01-01" });
assert.equal(paidOff(data), 123.45);
assert.equal(data.currentBalance, base.currentBalance);
assert.deepEqual(data.planEntries, base.planEntries);
assert.throws(() => run(data, { type: "debt-progress", id: id(), opening: true, amount: 500, date: "2026-01-01" }), /already saved/);
assert.equal(paidOff({ ...data, plannedPayments: [{ id: id(), amount: 900, status: "paid", planType: "advance" }] }), 123.45);
const noCash = { ...pay, deductCash: false, previousDebt: 200 };
data = run(data, noCash);
assert.equal(data.currentBalance, 500);
assert.equal(data.planEntries[0].balance, 150);
assert.equal(data.planEntries[0].paymentsRemaining, 1);
assert.equal(data.planEntries[0].dueDate, "2026-02-28");
assert.equal(paidOff(data), 173.45);
assert.deepEqual(run(data, noCash), data);
assert.equal(isDueOn(data.planEntries[0], "2026-02-28"), true);
assert.equal(isDueOn(data.planEntries[0], "2026-03-31"), false);
assert.throws(() => run(data, { ...pay, id: id(), deductCash: false, previousDebt: 200 }), /debt balance changed/);
assert.throws(() => run(data, { ...pay, id: id(), deductCash: true, previousCash: 600 }), /Cash changed/);
const withCash = run(data, { ...pay, id: id(), deductCash: true, previousCash: 500 });
assert.equal(withCash.currentBalance, 450);
assert.equal(withCash.planEntries[0].balance, 100);
assert.equal(withCash.planEntries[0].paymentsRemaining, 0);
assert.equal(withCash.planEntries[0].isActive, true, "An ended schedule must not forgive unpaid debt.");
assert.equal(debtRemaining(withCash).low, 100);
const progressOnly = { ...pay, id: id(), deductCash: false, progressOnly: true, amount: 17.55 };
const credit = run(data, progressOnly);
assert.equal(credit.currentBalance, data.currentBalance);
assert.deepEqual(credit.planEntries, data.planEntries);
assert.equal(paidOff(credit), 191);
assert.deepEqual(run(credit, progressOnly), credit);
assert.throws(() => commandSchema.parse({ ...progressOnly, deductCash: true }));
assert.throws(() => commandSchema.parse({ ...progressOnly, resolve: true }));
const globalCredit = run(credit, { type: "debt-progress", id: id(), amount: 9, date: "2026-01-01" });
assert.equal(paidOff(globalCredit), 200);
assert.equal(globalCredit.currentBalance, credit.currentBalance);
assert.deepEqual(globalCredit.planEntries, credit.planEntries);
const resolved = run(data, { ...pay, id: id(), amount: 150, resolve: true, deductCash: false });
assert.equal(resolved.planEntries[0].balance, 0);
assert.equal(resolved.planEntries[0].isActive, false);
assert.equal(resolved.currentBalance, 500);
assert.equal(paidOff(resolved), 323.45);
assert.throws(() => run(data, { ...pay, id: id(), amount: 151, deductCash: false }), /exceeds/);
const unknown = debtRemaining({ ...base, planEntries: [{ ...debt, balance: undefined }, { ...debt, id: "range", balance: 30, balanceHigh: 50, isApproximate: true }] });
assert.deepEqual(unknown, { low: 30, high: 50, unknown: 1, approximate: true });
console.log("Debt progress checks passed: explicit cash choice, progress-only credits, stale confirmations, finite repeats, and unpaid-balance preservation.");
