import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { SEED } from "../lib/ledger/seed.ts";
import { importLegacy } from "../lib/ledger/import-legacy.ts";
import { applyCommand, commandSchema } from "../lib/ledger/commands.ts";
import { migrate } from "../lib/ledger/ledger.ts";

let data = migrate(structuredClone(SEED), SEED);
const id = () => crypto.randomUUID();
const apply = command => applyCommand(data, commandSchema.parse(command), new Date().toISOString());
data = apply({ type: "reconcile", id: id(), amount: 59 });
const income = { type: "entry", id: id(), entry: { type: "income", name: "Regression income", amount: 2000, date: "2026-08-31", category: "Work" } };
data = apply(income); assert.equal(data.currentBalance, 2059);
assert.equal(apply(income).currentBalance, 2059);
data = apply({ type: "payment", id: id(), entryId: "b1", amount: 700, date: "2026-08-31" });
assert.equal(data.currentBalance, 1359);
const previous = structuredClone(data.planEntries.find(e => e.id === "s1"));
data = apply({ type: "save-item", id: id(), previous, entry: { ...previous, amount: 25 } });
assert.equal(data.currentBalance, 1359);
assert.throws(() => apply({ type: "save-item", id: id(), previous, entry: { ...previous, amount: 30 } }), /changed/);
assert.throws(() => commandSchema.parse({ ...income, extra: "injected" }));
assert.throws(() => commandSchema.parse({ type: "payment", id: id(), entryId: "b1", amount: 1.234, date: "2026-08-31" }));
const old = [{ id: id(), name: "Macy's (PRA)", amount: "111.07", kind: "debt", category: "Debt", paid: false, entry_date: "2026-08-20", created_at: "2026-08-21T00:00:00Z", updated_at: "2026-08-21T00:00:00Z" },
  { id: id(), name: "Daycare", amount: "340.00", kind: "bill", category: "Child Support", paid: true, entry_date: "2026-08-20", created_at: "2026-08-21T00:00:00Z", updated_at: "2026-08-21T00:00:00Z" }];
const imported = importLegacy(old, SEED);
assert.equal(imported.balanceSet, false); assert.equal(imported.currentBalance, 0);
assert.equal(imported.transactions.length, 1); assert.equal(imported.planEntries.length, 37);
assert.equal(imported.planEntries.find(e => e.name === "Macy's PRA").balance, 111.07);
const root = new URL("../", import.meta.url);
const context = readFileSync(new URL("app/finances/ledger/context.tsx", root), "utf8");
assert.doesNotMatch(context, /localStorage|SEED|service_role|SERVICE_ROLE/);
assert.match(context, /\/api\/finances\/ledger/);
const pkg = JSON.parse(readFileSync(new URL("package.json", root), "utf8"));
assert.ok(pkg.dependencies?.next || pkg.devDependencies?.next);
assert.ok(!pkg.dependencies?.vite && !pkg.devDependencies?.vite);
const css = readFileSync(new URL("app/finances/ledger/ledger.css", root), "utf8");
assert.doesNotMatch(css, /@import|:root/);
for (const route of ["finances", "finances-form", "finances-plan"]) assert.ok(readFileSync(new URL(`app/${route}/page.tsx`, root), "utf8"));
console.log("PASS: server commands, replay-safe money, stale edits, strict input, legacy preservation, Next.js routes, scoped CSS, no Figma/Vite runtime.");
